const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async()=>{
 const systemChromium=require('node:fs').existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined;
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||systemChromium});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL||'http://localhost:5173',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.service-card').count(),8);
 assert.equal(await page.locator('#total').innerText(),'0 BYN');
 await page.locator('[data-add="0"]').click();
 await page.locator('[data-add="1"]').click();
 assert.match(await page.locator('#total').innerText(),/от 60 BYN/);
 await page.locator('[data-key="0-0"] [data-step="1"]').click();
 assert.match(await page.locator('#total').innerText(),/от 90 BYN/);
 await page.locator('[data-select="2"]').selectOption('2');
 await page.locator('[data-add="2"]').click();
 assert.match(await page.locator('#total').innerText(),/от 165 BYN/);
 await page.locator('[data-remove="1-0"]').click();
 assert.match(await page.locator('#total').innerText(),/от 135 BYN/);
 await page.locator('[data-key="0-0"] input').fill('3');
 await page.locator('[data-key="0-0"] input').press('Tab');
 assert.match(await page.locator('#total').innerText(),/от 165 BYN/);
 await page.reload({waitUntil:'networkidle'});
 assert.match(await page.locator('#total').innerText(),/от 165 BYN/);
 await page.locator('#booking-button').click();
 assert.equal(await page.locator('dialog').evaluate(e=>e.open),true);
 assert.match(await page.locator('#booking-summary').innerText(),/Шиномонтаж R16/);
 assert.match(await page.locator('#booking-summary').innerText(),/от 165 BYN/);
 await page.keyboard.press('Escape');
 await page.locator('#clear-cart').click();
 assert.match(await page.locator('#total').innerText(),/^0 BYN$/);
 await page.locator('[data-add="0"]').click();
 await page.locator('[data-key="0-0"] input').fill('0');
 await page.locator('[data-key="0-0"] input').press('Tab');
 assert.equal(await page.locator('.quantity input').inputValue(),'1');
 await page.locator('[data-key="0-0"] input').fill('999');
 await page.locator('[data-key="0-0"] input').press('Tab');
 assert.equal(await page.locator('.quantity input').inputValue(),'99');
 await page.locator('#clear-cart').click();
 await page.evaluate(()=>document.activeElement.blur()); await page.waitForTimeout(2600);
 await page.screenshot({path:'/tmp/desktop.png',fullPage:true});
 for(const width of [390,768,1440]){
  await page.setViewportSize({width,height:900});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`Overflow at ${width}`);
 }
 await page.setViewportSize({width:390,height:844});
 await page.locator('.menu-toggle').click();
 assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
 await page.locator('nav a[href="#services"]').click();
 assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'false');
 await page.locator('#season-add').click();
 assert.equal(await page.locator('[data-select="2"]').evaluate(e=>e===document.activeElement),true);
 await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(500);
 await page.screenshot({path:'/tmp/mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 assert.equal(await page.locator('img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)),true);
 console.log('PASS: cart arithmetic, quantities, deletion, persistence, booking summary, mobile menu, season shortcut, images, no overflow at 390/768/1440, no JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
